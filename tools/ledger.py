"""Behavior-ledger parser and parity coverage report (FTL parity workstream, D053).

    python tools/ledger.py                 print the coverage per system
    python tools/ledger.py --write         also write docs/research/parity_report.md
    python tools/ledger.py --ledger <md>   read another ledger file (the unit test uses this)

Reads docs/research/behavior-ledger.md, whose rows have a strict format: a level-3 heading
"### L-<SYS>-<nn>: <claim>" followed by eight "- Field: value" lines (Kind, Behavior, Target,
Evidence, Test, Wrong value, Core, Status). Coverage of a system = passing number, shape and rule
rows over those rows in scope (waived rows leave the scope); feel rows are listed apart. A system is
at rough parity at 80% or more with no failing core row (docs/research/ftl-difftest-plan.md).
Reads committed files only; never research_private/.
"""
import argparse
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
LEDGER = os.path.join(ROOT, "docs", "research", "behavior-ledger.md")
REPORT = os.path.join(ROOT, "docs", "research", "parity_report.md")

FIELDS = ["Kind", "Behavior", "Target", "Evidence", "Test", "Wrong value", "Core", "Status"]
KINDS = {"number", "shape", "rule", "feel"}
HEAD = re.compile(r"^### (L-([A-Z]+)-([A-Z0-9]+)): (.+)$")
FIELD = re.compile(r"^- ([A-Za-z ]+): (.*)$")
SCOPE_LINE = re.compile(r"Stewart picked inventory .*?so the ((?:L-[A-Z]+,?\s+(?:and\s+)?)+)", re.S)
PARITY_AT = 0.8


class LedgerError(Exception):
    pass


def parse(text: str) -> list:
    """Rows as dicts {id, system, claim, <fields>, status_word}. Raises LedgerError on a bad row."""
    rows = []
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        m = HEAD.match(lines[i])
        if not m or m.group(1) == "L-<SYS>-<nn>":
            i += 1
            continue
        row = {"id": m.group(1), "system": m.group(2), "claim": m.group(4).strip()}
        for f in FIELDS:
            i += 1
            fm = FIELD.match(lines[i]) if i < len(lines) else None
            if not fm or fm.group(1) != f:
                raise LedgerError("%s: expected field \"%s\" at line %d" % (row["id"], f, i + 1))
            row[f] = fm.group(2).strip()
        if row["Kind"] not in KINDS:
            raise LedgerError("%s: unknown kind \"%s\"" % (row["id"], row["Kind"]))
        if row["Core"] not in ("yes", "no"):
            raise LedgerError("%s: Core must be yes or no" % row["id"])
        word = row["Status"].split(" ")[0].strip("(),")
        if word not in ("open", "passing", "failing", "waived"):
            raise LedgerError("%s: unknown status \"%s\"" % (row["id"], row["Status"]))
        if word == "waived" and not re.search(r"D\d{3}", row["Status"]):
            raise LedgerError("%s: a waived row names its decision (Dnnn)" % row["id"])
        row["status_word"] = word
        rows.append(row)
        i += 1
    ids = [r["id"] for r in rows]
    dup = sorted({x for x in ids if ids.count(x) > 1})
    if dup:
        raise LedgerError("duplicate row ids: %s" % ", ".join(dup))
    return rows


def scope(text: str) -> list:
    """System codes in scope, from the ledger's scope sentence ("... so the L-UPG, L-RWD and L-ENV rows")."""
    m = SCOPE_LINE.search(text)
    return re.findall(r"L-([A-Z]+)", m.group(1)) if m else []


def coverage(rows: list, systems: list) -> list:
    out = []
    for sys_code in systems:
        mine = [r for r in rows if r["system"] == sys_code]
        hard = [r for r in mine if r["Kind"] != "feel" and r["status_word"] != "waived"]
        passing = [r for r in hard if r["status_word"] == "passing"]
        failing_core = [r["id"] for r in hard if r["status_word"] == "failing" and r["Core"] == "yes"]
        frac = len(passing) / len(hard) if hard else 0.0
        out.append({
            "system": sys_code, "rows": len(mine), "in_scope": len(hard), "passing": len(passing),
            "failing": sum(1 for r in hard if r["status_word"] == "failing"),
            "open": sum(1 for r in hard if r["status_word"] == "open"),
            "waived": sum(1 for r in mine if r["status_word"] == "waived"),
            "feel": [(r["id"], r["status_word"]) for r in mine if r["Kind"] == "feel"],
            "coverage": frac, "failing_core": failing_core,
            "parity": frac >= PARITY_AT and not failing_core,
        })
    return out


def report(cov: list, rows: list) -> str:
    lines = ["# Parity report", "", "Generated by `python tools/ledger.py --write` from "
             "`docs/research/behavior-ledger.md` (Inner Sun values and pass or fail only).", "",
             "| system | rows | in scope | passing | failing | open | waived | coverage | parity |",
             "|---|---|---|---|---|---|---|---|---|"]
    for c in cov:
        lines.append("| %s | %d | %d | %d | %d | %d | %d | %d%% | %s |" % (
            c["system"], c["rows"], c["in_scope"], c["passing"], c["failing"], c["open"], c["waived"],
            round(100 * c["coverage"]), "yes" if c["parity"] else "no"))
    lines += ["", "Feel rows (judged by critics and Stewart, not counted in coverage):", ""]
    for c in cov:
        for rid, st in c["feel"]:
            lines.append("- %s: %s" % (rid, st))
    lines += ["", "## Rows", "", "| row | kind | core | status | claim |", "|---|---|---|---|---|"]
    systems = {c["system"] for c in cov}
    for r in rows:
        if r["system"] in systems:
            lines.append("| %s | %s | %s | %s | %s |" % (r["id"], r["Kind"], r["Core"], r["Status"], r["claim"]))
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ledger", default=LEDGER)
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    text = open(a.ledger, encoding="utf-8").read()
    try:
        rows = parse(text)
    except LedgerError as e:
        print("ledger: FORMAT ERROR: %s" % e)
        return 1
    systems = scope(text)
    cov = coverage(rows, systems)
    for c in cov:
        print("%-4s %2d/%-2d passing (%3d%%), %d failing, %d open, %d waived, parity %s%s" % (
            c["system"], c["passing"], c["in_scope"], round(100 * c["coverage"]), c["failing"], c["open"],
            c["waived"], "yes" if c["parity"] else "no",
            (" (failing core: %s)" % ", ".join(c["failing_core"])) if c["failing_core"] else ""))
    print("ledger: %d rows, %d systems in scope" % (len(rows), len(systems)))
    if a.write:
        with open(REPORT, "w", encoding="utf-8", newline="\n") as f:
            f.write(report(cov, rows))
        print("ledger: wrote %s" % os.path.relpath(REPORT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
